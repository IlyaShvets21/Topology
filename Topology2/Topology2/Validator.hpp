/************************************************************************************
 *  @file   Validator.hpp
 *  @brief  Файл содержит необходимые данные, для проверки корректности тестов
 ************************************************************************************/

#pragma once
#include "Reader.hpp"
#include <QString>
#include <QVector>

class Validator {
public:

    /************************************************************************************
    *  @brief  Функции проверки завершенности групп
    ***********************************************************************************/
    static bool isComplete(const DesignData& d, QString& error);
    static bool isComplete(const BlockData& b, QString& error);
    static bool isComplete(const NetsData& n, QString& error);

    /************************************************************************************
    *  @brief  Функция проверки уникальности имен блоков
    ***********************************************************************************/
    static bool checkUniqueBlockIds(const QVector<BlockData>& blocks, QString& error);

    /************************************************************************************
    *  @brief  Функция проверки согласованности парной последовательности
    ***********************************************************************************/
    static bool checkSequencePair(const FileData& data, QString& error);

    /************************************************************************************
    *  @brief  Функция проверки корректности параметров размещения
    ***********************************************************************************/
    static bool checkDecoderParams(const DecoderParams& p, QString& error);

    /************************************************************************************
    *  @brief  Функция проверки корректности булевых значений
    ***********************************************************************************/
    static bool parseBool(const QString& value, bool& out, QString& error, const QString& fieldName = "value");

    /************************************************************************************
    *  @brief  Функция комплексной проверки
    ***********************************************************************************/
    static bool validateAll(const FileData& data, QString& error);
};